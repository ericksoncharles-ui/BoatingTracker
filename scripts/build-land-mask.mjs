// Generates src/landMask.generated.js — the land/water bitmap the router uses
// to guarantee a course stays in the water.
//
// Run with: npm run landmask:build
//
// Source is @geo-maps/earth-coastlines-1m, an OpenStreetMap-derived coastline
// with 1 m absolute error (ODbL). It is a 38 MB world file and stays a
// devDependency — only the clipped, rasterized mask is committed.
//
// Why a raster and not the polygons: the router asks "is this point water" and
// "does this 40 NM chord touch land" thousands of times per trip. Against
// polygons that is a point-in-polygon test over a 226k-vertex continent ring;
// against a bitmap it is one array index. The whole covered region costs 768 KB
// raw and about 29 KB gzipped, which is worth spending to have every leg
// checked against a real shoreline instead of a dozen hand-placed circles.

import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const here = path.dirname(fileURLToPath(import.meta.url))
const root = path.join(here, '..')

// The app's waters — Throgs Neck west to past Nantucket east — with enough
// margin that a route near the edge is still tested against real shoreline.
const BOX = { west: -74.05, east: -69.70, south: 40.60, north: 42.20 }

// ~89 m x ~115 m cells. The source coastline carries roughly 180 m between
// vertices in this region, so a finer grid would only sharpen the staircase on
// data that is not itself that precise.
const COLS = 4096
const ROWS = 1536

const source = path.join(root, 'node_modules/@geo-maps/earth-coastlines-1m/map.geo.json')
if (!fs.existsSync(source)) {
  console.error('Missing @geo-maps/earth-coastlines-1m. Run: npm install')
  process.exit(1)
}

console.log('reading coastline…')
const raw = JSON.parse(fs.readFileSync(source, 'utf8'))
const polys = raw.geometries[0].coordinates

const dLat = (BOX.north - BOX.south) / ROWS
const dLng = (BOX.east - BOX.west) / COLS

// Scanline fill, even-odd, over the *unclipped* world rings.
//
// Clipping the rings to the box first seems the obvious optimization and is a
// trap: this coastline weaves in and out of any box you draw around it, and the
// stitched-up clipped ring flips the inside/outside parity in exactly the
// convoluted places — Greenwich Point, the Norwalk islands — the router most
// needs to get right. Bucketing whole-world edges by row costs little and keeps
// the parity globally correct.
const buckets = Array.from({ length: ROWS }, () => [])
let edges = 0
for (const poly of polys) {
  // Outer ring and holes alike become edges: even-odd then renders a lake
  // inside a landmass as not-land, which is the correct answer for a boat.
  for (const ring of poly) {
    for (let i = 0; i < ring.length; i++) {
      const a = ring[i]
      const b = ring[(i + 1) % ring.length]
      if (a[1] === b[1]) continue
      const loLat = Math.min(a[1], b[1])
      const hiLat = Math.max(a[1], b[1])
      if (hiLat < BOX.south || loLat > BOX.north) continue
      const r0 = Math.max(0, Math.floor((loLat - BOX.south) / dLat))
      const r1 = Math.min(ROWS - 1, Math.ceil((hiLat - BOX.south) / dLat))
      for (let r = r0; r <= r1; r++) buckets[r].push(a[0], a[1], b[0], b[1])
      edges++
    }
  }
}
console.log(`edges crossing the region's latitudes: ${edges}`)

const land = new Uint8Array(COLS * ROWS)
for (let r = 0; r < ROWS; r++) {
  const y = BOX.south + (r + 0.5) * dLat
  const bucket = buckets[r]
  const xs = []
  for (let i = 0; i < bucket.length; i += 4) {
    const ax = bucket[i], ay = bucket[i + 1], bx = bucket[i + 2], by = bucket[i + 3]
    if ((ay <= y && by > y) || (by <= y && ay > y)) {
      xs.push(ax + ((y - ay) / (by - ay)) * (bx - ax))
    }
  }
  if (xs.length < 2) continue
  xs.sort((p, q) => p - q)
  for (let i = 0; i + 1 < xs.length; i += 2) {
    if (xs[i + 1] < BOX.west || xs[i] > BOX.east) continue
    const c0 = Math.max(0, Math.ceil((xs[i] - BOX.west) / dLng - 0.5))
    const c1 = Math.min(COLS - 1, Math.floor((xs[i + 1] - BOX.west) / dLng - 0.5))
    for (let c = c0; c <= c1; c++) land[r * COLS + c] = 1
  }
}

const bytes = new Uint8Array(Math.ceil(land.length / 8))
for (let i = 0; i < land.length; i++) if (land[i]) bytes[i >> 3] |= 1 << (i & 7)

let landCells = 0
for (let i = 0; i < land.length; i++) landCells += land[i]

const b64 = Buffer.from(bytes).toString('base64')
const out = `// GENERATED by scripts/build-land-mask.mjs — do not edit by hand.
//
// Land/water bitmap for the app's waters, one bit per cell, row-major from the
// south-west corner. Derived from OpenStreetMap coastlines via
// @geo-maps/earth-coastlines-1m (ODbL). Regenerate with: npm run landmask:build

export const LAND_MASK = {
  west: ${BOX.west},
  east: ${BOX.east},
  south: ${BOX.south},
  north: ${BOX.north},
  cols: ${COLS},
  rows: ${ROWS},
  bits: '${b64}',
}
`
const dest = path.join(root, 'src/landMask.generated.js')
fs.writeFileSync(dest, out)

const cellW = dLng * 111320 * Math.cos(41.1 * Math.PI / 180)
const cellH = dLat * 110570
console.log(`grid ${COLS}x${ROWS}, cell ~${cellW.toFixed(0)} m x ${cellH.toFixed(0)} m`)
console.log(`land ${(landCells / land.length * 100).toFixed(1)}% of the box`)
console.log(`wrote ${path.relative(root, dest)} (${(out.length / 1024).toFixed(0)} KB base64)`)
